import '../models/task.dart';

/// 任务查询与取消（§12.1 / §8）
///
/// ─────────────────────────────────────────────────────────
/// 【这一层的存在本身就是 §8.4 那条硬规则的执行者】
///
/// §8.4：「任务生命周期完全归服务端，客户端只是观察者。**绝不**把任务状态
/// 存在 App 内存里；App 重开必须能从服务端拉回全部进行中任务。」
///
/// 换句话说：**这个 repository 是任务状态的唯一入口**。
/// 页面里不许有「我把状态存在自己身上」这种事 ——
/// 想看任务，就调 [fetchActive]，永远从服务端要。
///
/// 这不只是为了正确性，也是为了让「关掉 App 再打开，任务还在」这件事
/// 不需要任何额外代码 —— 因为它本来就每次都重新拉。
/// ─────────────────────────────────────────────────────────
abstract interface class TaskRepository {
  /// 进行中的任务（`?status=active`）。
  ///
  /// 对应 §11.3 里的非终态：`pending` / `queued` / `submitted`。
  /// 首页顶部的「进行中任务条」和作品页的「进行中」分段都用它。
  Future<List<Task>> fetchActive();

  /// 已结束的任务（`?status=done`）。
  ///
  /// 对应五个终态：`succeeded` / `failed` / `rejected` / `canceled` / `expired`。
  /// **注意这里包含失败和取消的**，不是只有成功的 ——
  /// 用户需要能看到「我那次失败了」并知道积分退回来了。
  Future<List<Task>> fetchDone();

  /// 单个任务详情（含排队位次）。
  ///
  /// 【为什么要单独一个详情接口，列表里不是已经有数据了】
  /// 因为列表刻意不返回全部字段（轮询时每 5 秒拉一次，带太多是浪费流量）。
  /// 详情页只在用户点进去时拉一次，可以给全。
  Future<Task> fetchDetail(String id);

  /// 取消任务。
  ///
  /// 【退不退钱取决于任务到哪一步了，这个差别是用户看得见的真金白银】
  /// §7.4 的退费政策：
  /// * `pending` / `queued` 取消 → **全额退回**（还没交给 provider，没花钱）
  /// * 已 `submitted` 取消 → **不退**（provider 已经在跑，钱已经花出去了）
  ///
  /// 所以 UI 在让用户确认取消之前，**必须根据当前状态给出正确的提示** ——
  /// 说「取消会全额退回」然后实际扣了钱，是最容易引发投诉的一类问题。
  Future<Task> cancel(String id);
}
