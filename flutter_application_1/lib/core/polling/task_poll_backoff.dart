/// 轮询间隔的退避策略
///
/// ─────────────────────────────────────────────────────────
/// 【为什么间隔是 5 秒 → 15 秒，而不是固定值】
///
/// 工程文档 §8.4 定的是「起 5 秒、退避到 15 秒」，这两个数字都不是拍脑袋：
///
/// * **5 秒起步**：图片是秒级完成的。用户提交完图片就盯着结果页，
///   如果轮询间隔是 15 秒，他会白等 15 秒才看到「已经好了」——
///   而这张图其实两秒前就完成了。
/// * **退避到 15 秒**：视频要十分钟。按 5 秒一直拉下去，十分钟是 120 次请求，
///   每次都带着 token 打后端 —— 一个用户这样，一万个用户就是每小时 720 万次
///   无意义的查询。而任务在十分钟这个尺度上，早 10 秒晚 10 秒知道结果
///   没有任何区别。
///
/// 【为什么退避不按「失败次数」而是按「已经轮询多久」】
/// 这两件事的动机完全不同，混在一起会互相干扰：
/// * 按失败退避，是**怕把服务端打挂**；
/// * 按时间退避，是**怕浪费电和流量**（任务本来就要跑十分钟）。
///
/// 这里需要的是后者。用「已经轮询多久」表达它，逻辑最简单，
/// 而且结果**可预测** —— 用户等待 3 分钟还是 30 分钟，间隔都是同一个曲线，
/// 不会因为中间抖了两下就变得忽快忽慢。
///
/// 【为什么单独抽成一个类】因为它是纯计算、没有副作用，可以单独跑单元测试。
/// 这类「有明确输入输出的规则」如果埋在一个 State 的定时器回调里，
/// 就只能靠手动改系统时间来验证。
/// ─────────────────────────────────────────────────────────
class TaskPollBackoff {
  const TaskPollBackoff({
    this.fast = const Duration(seconds: 5),
    this.slow = const Duration(seconds: 15),
    this.fastTicks = 12,
  });

  /// 前几个周期的间隔。
  final Duration fast;

  /// 退避之后的间隔。
  final Duration slow;

  /// 前多少个周期用 [fast]。
  ///
  /// 12 × 5 秒 = 1 分钟。也就是说**一分钟后**才退避到 15 秒。
  /// 这个分界线对应的是「图片大约几秒、视频要十分钟」这件事：
  /// 前一分钟是最可能出结果的时候，值得勤快一点。
  final int fastTicks;

  /// 第 [tick] 次轮询之前的等待时长。
  ///
  /// [tick] 从 0 开始（第一次轮询用 `delayFor(0)`）。
  Duration delayFor(int tick) {
    // 负数或异常入参不该让定时器算出奇怪的值，兜底成最短间隔
    if (tick < fastTicks) return fast;
    return slow;
  }
}
