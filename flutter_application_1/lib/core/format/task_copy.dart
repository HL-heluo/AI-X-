import '../constants/task_status.dart';

/// 任务相关的**用户可见文案** —— 和 `credit_format.dart` 同样的道理：
/// 同一句话要在多个地方出现时，只能有一个出处。
///
/// ─────────────────────────────────────────────────────────
/// 【为什么「任务为什么没成功」这句话必须集中】
///
/// 它要在**两个地方**出现：结果页（用户刚提交完，页面自动跳到那里）
/// 和任务详情页（用户从作品页点进去回看）。
///
/// 这两处如果各写一份，迟早会漂移 —— 比如详情页补上了「积分已退回」，
/// 结果页忘了补。那么同一个失败，用户在结果页看到的是
/// 「生成失败」，在详情页看到的是「生成失败，积分已全部退回」。
/// 他会立刻开始怀疑前者是不是没退钱。
/// ─────────────────────────────────────────────────────────
class TaskCopy {
  TaskCopy._();

  /// 任务走到终态但**没成功**时，给用户的一句解释。
  ///
  /// 返回 null 表示「这张状态不需要解释」（还在跑、或者已经成功了）。
  ///
  /// 【为什么每一句都要提积分】因为这是用户最关心的第二件事
  /// （第一件是「我的东西好了吗」）。§7.4 的政策是失败一定全额退回，
  /// 但用户不会去读政策 —— 他只会在没看到钱回来的时候来问。
  /// 把「已经退回来了」写进这句话里，是最省事也最有效的做法。
  static String? problemText(TaskStatus status) => switch (status) {
        TaskStatus.rejected =>
          '这次的内容没有通过审核。可以改一改提示词再试一次 —— 积分已经退回来了。',
        TaskStatus.failed => '生成服务这次没有返回结果。积分已经退回来了，重试不需要额外沟通。',
        TaskStatus.expired => '这个任务超过了生成服务的时间窗口，已经作废。积分已经退回来了。',
        // 用户自己取消的，不用解释；成功和进行中更没有可解释的
        TaskStatus.canceled => null,
        TaskStatus.succeeded => null,
        TaskStatus.pending || TaskStatus.queued || TaskStatus.submitted => null,
      };
}
