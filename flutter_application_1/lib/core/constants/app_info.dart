/// ─────────────────────────────────────────────────────────
/// 产品名与版本号的**唯一出处**
///
/// 【为什么值得单独一个文件放一个字符串】
/// 因为产品名（§18-5 尚未定名）散落在**四个互不相干的地方**：
/// Dart 里的 `MaterialApp.title`、`web/index.html` 的 `<title>`、
/// `web/manifest.json` 的 `name`、Android 的 `android:label`。
///
/// 前三处已经统一到这个名字上（B7），第四处也做了 —— 而且发现
/// 当初担心的「android:label 牵扯签名」是**记错了**：
/// 牵扯签名的是 **applicationId**，显示名和它没有关系，
/// 改显示名既不换包、也不影响已安装用户的升级。
///
/// 【那还剩什么没统一】原生清单和 HTML 读不到 Dart 常量，
/// 这三处是**手工同步**的 —— 所以 `test/copy_guards_test.dart`
/// 里有一条测试盯着它们，改了一边忘了另一边会红。
///
/// 【现在的值是占位】"AI 视频创作" 是**中性描述**，不是最终品牌名。
/// 用中性描述而不是继续挂着旧的「AI 聚合平台」，是因为后者属于
/// 已经作废的电商业务（见工程文档开头那次需求重写），
/// 留着它会让新同事以为这还是个电商项目。
/// ─────────────────────────────────────────────────────────
class AppInfo {
  AppInfo._();

  /// 产品名。**改这里之前先读上面那段注释。**
  static const String appTitle = 'AI 视频创作';

  /// 展示用的版本号。
  ///
  /// 【为什么要有它】设置页要显示。硬编码在页面里的话，
  /// 每次发版都得记得改两处（`pubspec.yaml` 和设置页），迟早对不上。
  /// 这里仍然是手写的 —— 想从 `pubspec.yaml` 自动读需要引入
  /// `package_info_plus`，为一个字符串不值当。
  static const String version = '0.1.0';

  /// 是否仍在使用中性占位名（设置页可以据此显示「内测中」之类的话）。
  static const bool isPlaceholderName = true;
}
