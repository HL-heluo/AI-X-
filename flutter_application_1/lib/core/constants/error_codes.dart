/// 平台对外错误码 —— **全项目唯一定义处**
///
/// 对应《工程文档.md》§12.3。这些是**我们自己后端**返回的业务错误码，
/// 不是即梦的原始错误码（即梦的 50411 / 50511 那些由后端翻译成下面这些）。
///
/// 【为什么要给错误码配类型】
/// 因为每种错误的**处理方式完全不同**：
/// 「积分不足」要引导用户去积分页，「提示词超长」要就地提示，
/// 「队列已满」要告诉用户稍后再试，「重复提交」则要**静默复用已有任务**（不能报错）。
/// 如果只把它们当成字符串，UI 层就得到处写 `if (msg == '...')`。
///
/// 【前端类比】≈ axios 拦截器里把 HTTP 状态码映射成一套带业务含义的 error.code。
enum ApiErrorCode {
  /// 可用余额不足 → 引导去积分页
  ///
  /// 注意「可用余额 = 总余额 − 冻结中」。有任务在跑时，
  /// 被冻结的那部分不能再用，所以看起来有余额也可能报这个错。
  ///
  /// 【文案为什么不是「请先充值」】因为 v1 **没有充值**（§7.6 的档位是
  /// v3 预留，积分页连一个入口都没有，`me_credits_test.dart` 专门守着这条）。
  /// 让用户去点一个不存在的东西，比什么都不说更糟 ——
  /// 他会去积分页翻三遍，然后来问「充值在哪」。
  /// 真正解释这件事的是那句弹窗（见两个生成页的 `_handleSubmitError`），
  /// 错误条只需要说清「是什么问题」。
  insufficientCredits(
    'INSUFFICIENT_CREDITS',
    400,
    '可用积分不足',
  ),

  /// 提示词超长或为空 → 就地提示
  invalidPrompt(
    'INVALID_PROMPT',
    400,
    '提示词不能为空，且不超过 2000 字',
  ),

  /// 参考图超限 → 就地提示
  imageTooLarge(
    'IMAGE_TOO_LARGE',
    400,
    '参考图过大，请压缩到 20MB 以内',
  ),

  /// 幂等键重复 → **静默复用已存在的任务，不弹错误**
  ///
  /// 这是防连点双扣的那道闸（客户端生成 UUID 作幂等键）。
  /// 用户双击生成按钮时应该无感，而不是看到一个红色报错。
  /// 所以这条文案正常**不会**被看到，留一个只是为了日志和兜底。
  duplicateRequest(
    'DUPLICATE_REQUEST',
    409,
    '这次提交已经收到，正在处理',
  ),

  /// 触发配额 → 提示每日上限（同时进行 ≤ 1、每日 ≤ 20）
  rateLimited(
    'RATE_LIMITED',
    429,
    '已达今日生成上限，请明天再试',
  ),

  /// 输入内容审核未通过 → 提示改写提示词
  ///
  /// 【别和任务状态 `rejected` 搞混】
  /// 这个码是**提交时**就被挡下来了（输入审核），任务压根没建；
  /// `TaskStatus.rejected` 是任务**建成之后**生成过程中被 provider 拦下（输出审核）。
  /// 两者用户可见的话术不同：前者「换个说法再试」，后者「这次生成未通过审核，积分已退回」。
  contentRejected(
    'CONTENT_REJECTED',
    422,
    '这段描述未通过审核，换个说法再试试',
  ),

  /// provider 失败 → 告知已全额退回，可重试
  providerError(
    'PROVIDER_ERROR',
    502,
    '生成失败，积分已全额退回，可以重新试一次',
  ),

  /// 队列已满 → 提示稍后再试
  queueSaturated(
    'QUEUE_SATURATED',
    503,
    '当前生成的人有点多，稍后再试',
  ),

  /// 邀请码无效 → 贴着输入框提示换一个
  ///
  /// ─────────────────────────────────────────────────────────
  /// 【为什么这一条是 F8 加的，而不是等后端建好了再说】
  ///
  /// §6.1 说注册必须带邀请码，那么「邀请码不对」就是注册路上**必然会遇到**
  /// 的一个失败。而 §12.3 的错误码表里没有它 —— 于是后端发什么码，
  /// 前端都认不出，`AppException.code` 为 null，
  /// 登录页的 `_friendlyMessage` 就会退回那句通用的
  /// **「连不上服务器，检查一下网络再试」**。
  ///
  /// 那是在**撒谎**：网络好得很，是邀请码打错了。用户会去关 Wi-Fi 重连、
  /// 换 4G、找客服说「你们服务器坏了」—— 而真正要改的就在他手边那个输入框里。
  /// 这与 B7′ 修掉的「请先充值」是同一类错误（让用户去解决一个不存在的问题），
  /// 所以趁 F8 动前端时一并堵上。
  ///
  /// 【为什么不等全部缺口一次补齐】§12.3 还缺 `UNAUTHORIZED` /
  /// `USERNAME_TAKEN` / `INVALID_CREDENTIALS` / `NOT_FOUND`，但这四个
  /// **前端已经能用 HTTP 状态码正确分支**（登录页看 401/409，`isUnauthorized`
  /// 看 401），不补也不会说错话。只有邀请码这一条会真的说错话。
  /// 其余的等 B2 真后端开始发这些码时再补，那时能拿真请求验，不用凭猜。
  /// ─────────────────────────────────────────────────────────
  inviteInvalid(
    'INVITE_INVALID',
    400,
    '邀请码无效，请确认后再试',
  );

  const ApiErrorCode(this.wire, this.httpStatus, this.defaultMessage);

  /// 与后端约定的字符串。序列化/比较只能用这个。
  final String wire;

  /// 对应的 HTTP 状态码。
  ///
  /// 【为什么要存它】一来便于断言和排查（日志里能对上），
  /// 二来 Mock 层要照着它返回正确的状态码，才能让错误处理代码走真实路径。
  final int httpStatus;

  /// 展示给用户的兜底文案。
  ///
  /// 【为什么要在这里写死】
  /// 后端返回的 `message` 是给开发看的（可能带堆栈、可能改口径），
  /// **不该直接糊到用户脸上**。但每个错误码总得有一句话可说 ——
  /// 若让每个页面自己编，同一个「积分不足」在创作页和作品页就会是两种说法。
  /// 集中一份，UI 想覆盖时再覆盖。
  final String defaultMessage;

  /// 按错误码字符串还原。认不出返回 null（宽松）——
  /// 错误码可能新增，但**认不出不该让整个错误处理崩掉**，
  /// 退化成「未知错误，请稍后重试」是更安全的选择。
  static ApiErrorCode? tryFromWire(String? wire) {
    if (wire == null) return null;
    for (final c in ApiErrorCode.values) {
      if (c.wire == wire) return c;
    }
    return null;
  }
}
