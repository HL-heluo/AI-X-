import '../../models/task.dart';

/// 「任务完成了」这件事的通知出口
///
/// ─────────────────────────────────────────────────────────
/// 【为什么必须有一个抽象，而不是直接调插件】
///
/// 工程文档 §8.4 要求：视频生成约 10 分钟，**完成时要发一条本地通知**。
/// 这条通知只有一种真实场景：用户提交完视频就走了（去回微信、去刷别的），
/// 十分钟后 App 可能在后台、可能已经被系统冻结 —— 这时候轮询拉到「已完成」，
/// 如果只在界面上改个状态，**用户根本看不见**，他会以为任务卡死了，
/// 然后第二天来问客服。
///
/// 但通知这个动作**不可测试、不可在 Web 上跑、失败了也不该影响主流程**：
/// * 在 widget 测试里，任何插件的平台通道都会抛 `MissingPluginException`；
/// * Web 上本地通知要走浏览器权限 + Service Worker，行为与移动端完全不同；
/// * 通知权限被用户拒绝时，任务本身**已经成功了**，不能因为通知发不出去
///   就让整条链路报错。
///
/// 所以这里做一层接口：轮询那头只管 `await notifier.notifyTaskFinished(task)`，
/// 不关心它是真通知、空实现还是测试替身。
/// ─────────────────────────────────────────────────────────
abstract interface class TaskNotifier {
  /// 通知用户「你那个任务有结果了」。
  ///
  /// 【实现约定】**永远不要抛异常**。调用点在轮询循环里，
  /// 一个抛出来的通知异常会把那一次轮询整个打断 ——
  /// 而任务状态的更新比一条通知重要得多。
  Future<void> notifyTaskFinished(Task task);
}

/// 什么都不做的实现
///
/// 【什么时候用它】
/// * Web（见 `taskNotifierProvider` 里的说明）；
/// * 任何「不想打扰用户」的场合。
///
/// 【为什么不做成 null】因为调用方就要到处写 `if (notifier != null)`，
/// 而「不通知」本身就是一种**明确的行为**，值得有一个名字。
class NoopTaskNotifier implements TaskNotifier {
  const NoopTaskNotifier();

  @override
  Future<void> notifyTaskFinished(Task task) async {}
}
