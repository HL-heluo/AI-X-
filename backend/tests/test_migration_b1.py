"""B1：迁移。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【为什么单独测迁移，而不是只测 `Base.metadata.create_all`】

因为**跑起来的库不是 `create_all` 建的，是迁移建的**。

`create_all` 直接照着模型建表，所以它永远和模型一致 ——
测它等于测「模型和我自己一致」，恒真、无信息量。

而迁移是**另一份**描述同一件事的产物，两者会漂移，漂移的方式还很隐蔽：

  · 有人改了 `models.py` 里某列的长度/可空性，忘了 `alembic revision`
    → 开发机上 `create_all` 起来一切正常，**部署时迁移建出来的库不对**；
  · 手改过迁移文件，改错了
    → 只有真正从空库升级上来才会暴露。

所以这里的做法是：**从空库跑真迁移**，再用 `alembic check`
问一句「现在再 autogenerate，还有没有差异」。这是唯一能同时
覆盖「迁移能跑」和「迁移与模型一致」两件事的测法。
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import pytest
from sqlalchemy import Engine, create_engine, inspect

ROOT = Path(__file__).resolve().parent.parent


def _config(db_url: str):  # noqa: ANN202 - 返回值是 alembic 的 Config
    from alembic.config import Config

    cfg = Config(str(ROOT / "alembic.ini"))
    # 【为什么要显式指定 script_location】`alembic.ini` 里写的是相对路径
    # `script_location = alembic`，它相对的是**当前工作目录**。
    # pytest 的工作目录不一定是仓库根（取决于从哪里调用），
    # 不钉死的话这条测试会在某些调用方式下找不到迁移目录。
    cfg.set_main_option("script_location", str(ROOT / "alembic"))
    return cfg


@pytest.fixture
def migrated_db(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[str]:
    """从空库跑一遍真迁移，产出一个已升级的库的 URL。

    【为什么要动环境变量和清缓存】因为 `alembic/env.py` 的 `_url()`
    读的是 `get_settings().database_url`，而 `get_settings` 带
    `lru_cache`。不清缓存的话，迁移会跑到**开发用的那个库**上 ——
    也就是这条测试会把开发机的库升一遍级，而不是用临时库。
    """
    from app.config import get_settings
    from app.database import reset_engine

    url = f"sqlite:///{(tmp_path / 'migrated.db').as_posix()}"
    monkeypatch.setenv("DATABASE_URL", url)
    get_settings.cache_clear()
    reset_engine()

    from alembic import command

    command.upgrade(_config(url), "head")

    yield url

    get_settings.cache_clear()
    reset_engine()


def test_迁移能从空库建出全部业务表(migrated_db: str) -> None:
    """B1 的门禁：迁移建全 7 表。

    【为什么断言的是**表名集合**而不是「表数量 = 7」】数量相等
    完全可能是「多了 1 张少了 1 张」。集合比较能说出差的是哪个。
    """
    engine: Engine = create_engine(migrated_db)
    try:
        names = set(inspect(engine).get_table_names())
    finally:
        engine.dispose()

    expected = {
        "users",
        "invite_codes",
        "credit_accounts",
        "credit_ledger",
        "tasks",
        "assets",
        "provider_calls",
        "chain_wallets",
        "chain_ops",
        "chain_state",
        "evidence_records",
        "work_publications",
        "work_holdings",
        "work_listings",
        "work_trades",
    }
    # alembic_version 是 Alembic 自己的记账表，不算业务表。
    names.discard("alembic_version")
    assert names == expected, f"迁移建的库和 §11.1 的表清单不一致：{names ^ expected}"


def test_幂等键唯一约束真的建在库里(migrated_db: str) -> None:
    """⚠️ 光在模型里写 `UniqueConstraint` 是不够的，它得**真的进到库里**。

    【为什么这条要从库里读约束、而不是读模型】因为迁移是手可以改的。
    有人为了「先跑通」把一条约束从迁移里删掉，模型里那份注释还写着
    「有唯一约束」—— 而数据库里没有，连点双扣就会真的扣两次。
    从库里读 constraint，才是问「实际有没有」。
    """
    engine: Engine = create_engine(migrated_db)
    try:
        uniques = inspect(engine).get_unique_constraints("tasks")
    finally:
        engine.dispose()

    columns = [tuple(sorted(u["column_names"])) for u in uniques]
    assert ("idempotency_key", "user_id") in columns, (
        f"tasks 的幂等键唯一约束没建出来。库里的唯一约束有：{columns}"
    )


def test_迁移与模型没有漂移(migrated_db: str) -> None:
    """⚠️ 守卫：`alembic check` —— 「现在再 autogenerate，还有差异吗」。

    ─────────────────────────────────────────────────────────
    【这条守卫挡的是最常发生的一类真实故障】

    有人改了 `models.py`（加一列、改个长度）却忘了生成迁移。
    此时：

      · 开发机上 `create_all` 或「迁移 + 手改库」起来一切正常，
        因为他本地库已经是对的；
      · 测试全绿（没有测试会为此红）；
      · **只有部署到一台干净的机器上，才会发现那一列不存在**。

    而那一刻的报错通常出现在某个不相关的接口上（`no such column`），
    排查方向会完全跑偏。

    `alembic check` 把这件事变成一个红灯。Alembic 1.9+ 提供，
    有差异时抛 `AutogenerateDiffsDetected`。
    ─────────────────────────────────────────────────────────
    """
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected

    try:
        command.check(_config(migrated_db))
    except AutogenerateDiffsDetected as exc:
        pytest.fail(
            "迁移与 models.py 已经漂移 —— 有人改了模型但没生成迁移。"
            "跑 `python -m alembic revision --autogenerate -m '...'`，"
            f"并**读一遍生成的脚本**（autogenerate 会漏东西）。\n{exc}"
        )


def test_迁移可以回滚干净(migrated_db: str) -> None:
    """downgrade 要真的能降回去。

    【为什么值得测】因为 downgrade 是最少被跑到的代码路径 ——
    写错了很久都没人发现，直到某次真的需要回滚时才发现降不下去。
    那时通常是在出故障、赶时间的时候。
    """
    from alembic import command

    cfg = _config(migrated_db)
    command.downgrade(cfg, "base")

    engine: Engine = create_engine(migrated_db)
    try:
        left = set(inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()

    assert left == set(), f"降级后还剩这些表：{left}"

    # 再升回去，确认迁移是可重复的（不是「降过一次就坏了」）
    command.upgrade(cfg, "head")
    engine = create_engine(migrated_db)
    try:
        again = set(inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()
    assert len(again) == 15, again
